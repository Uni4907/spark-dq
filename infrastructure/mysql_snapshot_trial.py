import json, os, secrets, subprocess, time, sys
from pathlib import Path

repo=Path(__file__).resolve().parents[1]
root=repo/'.runtime'/('mysql-snapshot-'+time.strftime('%Y%m%d-%H%M%S')+'-'+secrets.token_hex(4));root.mkdir(mode=0o700,parents=True)
sys.path.insert(0,str(repo/'infrastructure'))
import cluster_lab
def run(args, **kw):
    return subprocess.run(args,check=True,timeout=kw.pop('timeout',120),**kw)
def output(args):
    return subprocess.check_output(args,timeout=30,text=True).strip()
name='sparkdq-t1a-'+secrets.token_hex(5)
password=secrets.token_hex(24); reader=secrets.token_hex(24)
env=root/'fixture.env'
fd=os.open(env,os.O_WRONLY|os.O_CREAT|os.O_EXCL,0o600)
with os.fdopen(fd,'w') as f:
    f.write('MYSQL_ROOT_PASSWORD='+password+'\nMYSQL_ROOT_HOST=%\nSNAPSHOT_TEST_ROOT_PASSWORD='+password+'\nSNAPSHOT_TEST_READER_PASSWORD='+reader+'\nSNAPSHOT_TEST_URL=jdbc:mysql://'+name+'-mysql:3306/?useSSL=false&allowPublicKeyRetrieval=true&connectTimeout=3000&socketTimeout=10000&zeroDateTimeBehavior=EXCEPTION&tinyInt1isBit=false\n')
plan={'project':name,'evidenceRoot':str(root),'network':name+'-net','volume':name+'-data','mysql':name+'-mysql','maven':name+'-maven','ports':[], 'primaryDeploymentTouched':False,'cleanup':[]}
(root/'fixture-plan.json').write_text(json.dumps(plan,indent=2))
mysql='mysql:8.4.8@sha256:2952e3be7807f06fc18de50b3ea1a632d5c70d63482ff7d7376fe3aa8999babf'
maven='maven:3.9.12-eclipse-temurin-17@sha256:a0603aab698040d9c94259f379ec0487da1678560748d6c7508483034033c53d'
try:
    network=cluster_lab.network_plan();plan['networkPlan']=network
    run(['docker','network','create','--internal','--subnet',network['default'],'--label','sparkdq.batch=t1a',plan['network']],stdout=subprocess.DEVNULL)
    run(['docker','volume','create','--label','sparkdq.batch=t1a',plan['volume']],stdout=subprocess.DEVNULL)
    run(['docker','run','-d','--name',plan['mysql'],'--network',plan['network'],'--memory','768m','--cpus','1','--env-file',str(env),'-v',plan['volume']+':/var/lib/mysql',mysql],stdout=subprocess.DEVNULL)
    deadline=time.monotonic()+110
    while time.monotonic()<deadline:
        result=subprocess.run(['docker','exec',plan['mysql'],'sh','-c','MYSQL_PWD="$MYSQL_ROOT_PASSWORD" mysql -u root -e "SELECT 1"'],stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL,timeout=5)
        if result.returncode==0:break
        time.sleep(2)
    else:raise TimeoutError('Isolated MySQL readiness')
    with (root/'maven-tests.log').open('x') as log:
        result=subprocess.run(['docker','run','--rm','--name',plan['maven'],'--network',plan['network'],'--memory','2g','--cpus','2','--env-file',str(env),'-v',str(repo)+':/src','-v','spark-dq-maven-cache:/root/.m2','-w','/src',maven,'mvn','-o','-B','-pl','backend','test'],stdout=log,stderr=subprocess.STDOUT,timeout=240)
    plan['testExitCode']=result.returncode
    reports=root/'surefire-reports';reports.mkdir()
    import shutil
    for report in (repo/'backend/target/surefire-reports').glob('TEST-*.xml'):shutil.copy2(report,reports/report.name)
    print('Maven exit:',result.returncode,flush=True)
finally:
    # No volumes are removed. Capture/stops affect only names generated by this run.
    for key in ('maven','mysql'):
        subprocess.run(['docker','stop','-t','10',plan[key]],stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL,timeout=20)
        plan['cleanup'].append({'container':plan[key],'action':'stop requested'})
    state=subprocess.run(['docker','inspect','--format','{{.State.Status}}',plan['mysql']],capture_output=True,text=True,timeout=15)
    plan['mysqlState']=state.stdout.strip() if state.returncode==0 else 'not created'
    plan['volumeRetained']=True
    (root/'fixture-result.json').write_text(json.dumps(plan,indent=2))
    env.unlink(missing_ok=True)
    print(json.dumps({k:v for k,v in plan.items() if k!='networkPlan'}),flush=True)
if plan.get('testExitCode')!=0:raise SystemExit(1)
