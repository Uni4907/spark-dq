SELECT entry FROM (
 SELECT CAST(JSON_ARRAY('table',TABLE_NAME,TABLE_TYPE,ENGINE,TABLE_COLLATION) AS CHAR) AS entry
 FROM information_schema.TABLES WHERE TABLE_SCHEMA=DATABASE()
 UNION ALL
 SELECT CAST(JSON_ARRAY('column',TABLE_NAME,COLUMN_NAME,ORDINAL_POSITION,COLUMN_TYPE,IS_NULLABLE,
 COLUMN_DEFAULT,EXTRA,CHARACTER_SET_NAME,COLLATION_NAME,GENERATION_EXPRESSION) AS CHAR)
 FROM information_schema.COLUMNS WHERE TABLE_SCHEMA=DATABASE()
 UNION ALL
 SELECT CAST(JSON_ARRAY('index',TABLE_NAME,INDEX_NAME,NON_UNIQUE,SEQ_IN_INDEX,COLUMN_NAME,
 COLLATION,SUB_PART,INDEX_TYPE,IS_VISIBLE,EXPRESSION) AS CHAR)
 FROM information_schema.STATISTICS WHERE TABLE_SCHEMA=DATABASE()
 UNION ALL
 SELECT CAST(JSON_ARRAY('fk',k.TABLE_NAME,k.CONSTRAINT_NAME,k.ORDINAL_POSITION,k.COLUMN_NAME,
 k.REFERENCED_TABLE_NAME,k.REFERENCED_COLUMN_NAME,r.UPDATE_RULE,r.DELETE_RULE,
 IF(k.REFERENCED_TABLE_SCHEMA=DATABASE(),'local',k.REFERENCED_TABLE_SCHEMA)) AS CHAR)
 FROM information_schema.KEY_COLUMN_USAGE k JOIN information_schema.REFERENTIAL_CONSTRAINTS r
 ON r.CONSTRAINT_SCHEMA=k.CONSTRAINT_SCHEMA AND r.CONSTRAINT_NAME=k.CONSTRAINT_NAME AND r.TABLE_NAME=k.TABLE_NAME
 WHERE k.TABLE_SCHEMA=DATABASE() AND k.REFERENCED_TABLE_NAME IS NOT NULL
 UNION ALL
 SELECT CAST(JSON_ARRAY('trigger',TRIGGER_NAME) AS CHAR) FROM information_schema.TRIGGERS WHERE TRIGGER_SCHEMA=DATABASE()
 UNION ALL
 SELECT CAST(JSON_ARRAY('routine',ROUTINE_NAME) AS CHAR) FROM information_schema.ROUTINES WHERE ROUTINE_SCHEMA=DATABASE()
 UNION ALL
 SELECT CAST(JSON_ARRAY('event',EVENT_NAME) AS CHAR) FROM information_schema.EVENTS WHERE EVENT_SCHEMA=DATABASE()
 UNION ALL
 SELECT CAST(JSON_ARRAY('check',TABLE_NAME,CONSTRAINT_NAME) AS CHAR) FROM information_schema.TABLE_CONSTRAINTS
 WHERE CONSTRAINT_SCHEMA=DATABASE() AND CONSTRAINT_TYPE='CHECK'
) metadata ORDER BY BINARY entry;
